class User extends Authenticatable implements HasMedia
{
    use HasApiTokens, HasFactory, Notifiable, HasRoles, SoftDeletes, InteractsWithMedia;

    const USER_AVATAR_COLLECTION = 'user_avatar';
    const USER_AVATAR_RESIZE_NAME = 'avatar_resize';
    const CONVERSION_SIZE = [
        'width' => '650',
        'height' => '415',
    ];

    /**
     * The attributes that are mass assignable.
     *
     * @var array<int, string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'status',
        'locked_at',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var array<int, string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * The attributes that should be cast.
     *
     * @var array<string, string>
     */
    protected $casts = [
        'email_verified_at' => 'datetime',
        'locked_at' => 'datetime',
        'password' => 'hashed',
        'status' => UserStatus::class,
    ];

    /**
     * The accessors to append to the model's array form.
     *
     * @var array
     */
    protected $appends = ['avatar_url'];
    protected $with = ['media'];

    /**
     * Get the URL of the user's avatar.
     *
     * @return Attribute
     */
    public function avatarUrl(): Attribute
    {
        return Attribute::make(
            fn($value) => $this->getFirstMediaUrl(self::USER_AVATAR_COLLECTION) ?: Vite::asset('resources/images/avatar-default.svg')
        );
    }

    /**
     * Get the user profile record associated with the user.
     *
     * @return HasOne<UserProfile>
     */
    public function userProfile(): HasOne
    {
        return $this->hasOne(UserProfile::class);
    }
}
